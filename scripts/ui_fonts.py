"""The campus faces, pulled out of the vendored toolkit for the back offices.

Owner answer to Q-19 (2026-10-17): the fonts are "whatever Campus uses and the PRI/INHS
pages", and the back offices move to them too. The vendored toolkit bundle confirms the
set: it embeds @font-face rules for Source Sans 3 (body) and Montserrat (headings), with
the font data already base64 inside the CSS.

The public pages get the faces from the whole bundle. The two back offices never loaded
it, so they named Montserrat and rendered Segoe UI instead, which is deviation PDT-03.
Naming the family without loading it would simply repeat that, so this module lifts the
seven @font-face rules out of the bundle and nothing else: no component styles to collide
with the back office's own.

build_site.py writes them to assets/fonts.css for the hosted page to link and cache;
admin_server.py stamps them straight into the Data Console, which serves no static files
and must work with no network.

Never regenerates assets/vendor: it only reads it.

Pure stdlib.
"""
import os, re

PROJ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUNDLE = os.path.join(PROJ, "assets", "vendor", "toolkit.local.css")
OUT = os.path.join(PROJ, "assets", "fonts.css")
FAMILIES = ("'Source Sans 3'", "'Montserrat'")

_FACE = re.compile(r"@font-face\{[^}]*\}")


def font_faces():
    """Every @font-face rule for the two campus faces, or "" when the bundle is absent.

    An empty answer is not a failure: without the bundle the pages fall back to the
    system stack, exactly as they do today, and build_site.py already refuses to build
    an online-only copy by accident.
    """
    if not os.path.isfile(BUNDLE):
        return ""
    with open(BUNDLE, encoding="utf-8") as f:
        css = f.read()
    keep = [m for m in _FACE.findall(css) if any(fam in m for fam in FAMILIES)]
    return "".join(keep)


def write_fonts_css():
    """Write assets/fonts.css for the hosted back office to link. Returns the path."""
    faces = font_faces()
    header = ("/* Generated by scripts/ui_fonts.py from assets/vendor/toolkit.local.css.\n"
              "   The campus faces for the hosted back office (Q-19, PDT-03). Do not edit:\n"
              "   rebuild with py scripts/build_site.py. */\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + faces + "\n")
    return OUT


if __name__ == "__main__":
    p = write_fonts_css()
    print("wrote %s (%d bytes)" % (p, os.path.getsize(p)))
